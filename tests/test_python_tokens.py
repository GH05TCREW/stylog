def test_25_7_myurl2_split_and_style():
    assert split_components("myURL2") == ["my", "URL2"]
    assert classify_style("myURL2") == "camel_lower"


def test_25_7_comment_features_and_noqa_marker():
    out = by_id(run_tokens(FIXTURE_25_7))
    assert out["code.python.comments.comment_count"].value.value == 1
    share = out["code.python.comments.comment_line_share"].value
    assert (share.numerator, share.denominator) == (1, 7)
    assert hist(out["code.python.comments.comment_length"]) == {4: 1}  # "noqa"
    assert cat(out["code.toolchain.python_comment_marker"]) == {"noqa": 1}


def test_25_7_fstring_fragments_are_not_string_tokens():
    out = by_id(run_tokens(FIXTURE_25_7))
    # f"{myURL2=}" produces FSTRING_* fragments only; no whole STRING token exists
    assert out["code.python.lexical.string_quote"].status == "insufficient_support"
    assert out["code.python.lexical.string_prefix"].status == "insufficient_support"


def test_registry_coverage_sorted():
    out = run_tokens(FIXTURE_25_7)
    owned = [f.feature_id for f in features_owned_by(ANALYZER_CODE_PYTHON_TOKENS)]
    assert [o.feature_id for o in out.observations] == sorted(owned)


# --- spec 8.6 / 8.7 ---


def test_number_forms():
    out = by_id(run_tokens(NUMBER_SRC))
    assert cat(out["code.python.lexical.number_form"]) == {
        "binary": 1,
        "decimal_integer": 2,
        "floating": 4,
        "hexadecimal": 1,
        "imaginary": 2,
        "octal": 1,
    }


def test_string_quote_and_prefix():
    out = by_id(run_tokens(STRING_SRC))
    # j = fr'fr' and k = Rf'rf' are f-strings: FSTRING_* fragments, never whole
    # STRING tokens, so they do not participate in quote/prefix (spec 8.7)
    assert cat(out["code.python.lexical.token_class"])["string_fragment"] == 6
    assert cat(out["code.python.lexical.string_quote"]) == {
        "'": 7,
        '"': 1,
        "'''": 1,
        '"""': 1,
    }
    assert cat(out["code.python.lexical.string_prefix"]) == {
        "": 5,
        "b": 1,
        "br": 1,
        "r": 1,
        "rb": 1,
        "u": 1,
    }


def test_tstring_and_fstring_fragments():
    out = by_id(run_tokens('t"Hi {x}"\nf"{y}"\n'))
    if sys.version_info >= (3, 14):
        expected = {
            "identifier": 2,
            "operator": 4,
            "string_fragment": 5,
        }
    else:
        # cpython.tokenize before 3.14 has no TSTRING_* tokens: t"Hi {x}"
        # lexes as NAME 't' followed by a plain STRING.
        expected = {
            "identifier": 2,
            "operator": 2,
            "string": 1,
            "string_fragment": 2,
        }
    assert cat(out["code.python.lexical.token_class"]) == expected


def test_soft_keywords():
    out = by_id(run_tokens("match = 1\ncase = 2\n_ = 3\n"))
    assert cat(out["code.python.lexical.token_class"]) == {
        "number": 3,
        "operator": 3,
        "soft_keyword": 3,
    }
    assert cat(out["code.python.lexical.keyword_distribution"]) == {
        "_": 1,
        "case": 1,
        "match": 1,
    }
    # soft keywords are not identifier occurrences
    assert out["code.python.naming.identifier_occurrence_length"].status == "insufficient_support"


