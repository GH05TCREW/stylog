# --- failure semantics (spec 8.1, 8.4, 25.9) ---


def test_tokenize_failure_is_atomic():
    ctx = make_ctx()
    artifact = make_artifact("def f(")
    facts = parse_python(artifact, ctx.config)
    assert facts.token_error_code == "PYTHON_TOKENIZE_ERROR"
    assert facts.tokens is None
    assert facts.tree is None
    out = PythonTokensAnalyzer().analyze(artifact, ctx, facts)
    assert all(o.status == "parser_error" for o in out.observations)
    assert len(out.observations) == len(features_owned_by(ANALYZER_CODE_PYTHON_TOKENS))
    assert [d.code for d in out.diagnostics] == ["PYTHON_TOKENIZE_ERROR"]


def test_ast_failure_keeps_token_features():
    out = by_id(run_tokens("x = 1\nif:\n    pass\n"))
    assert out["code.python.lexical.token_class"].status == "ok"


def test_decode_error_conflict():
    raw = b"\xef\xbb\xbf# coding: latin-1\nx = 1\n"
    ctx = make_ctx()
    artifact = make_artifact_bytes(raw)
    facts = parse_python(artifact, ctx.config)
    assert facts.decode_error_code == "PYTHON_ENCODING_ERROR"
    assert facts.tokens is None and facts.tree is None
    out = PythonTokensAnalyzer().analyze(artifact, ctx, facts)
    assert all(o.status == "parser_error" for o in out.observations)
    assert [d.code for d in out.diagnostics] == ["PYTHON_ENCODING_ERROR"]


def test_latin1_cookie_decodes():
    raw = "# coding: latin-1\nx = 'café'\n".encode("latin-1")
    ctx = make_ctx()
    artifact = make_artifact_bytes(raw)
    facts = parse_python(artifact, ctx.config)
    assert facts.decode_error_code is None
    assert facts.encoding == "iso-8859-1"
    assert facts.tokens is not None and facts.tree is not None


def test_utf8_bom_accepted():
    raw = b"\xef\xbb\xbfx = 1\n"
    ctx = make_ctx()
    artifact = make_artifact_bytes(raw)
    facts = parse_python(artifact, ctx.config)
    assert facts.decode_error_code is None
    assert facts.encoding == "utf-8-sig"


def test_python_disabled():
    config = StylogConfig(
        analysis=AnalysisConfig(
            code=CodeAnalysisConfig(python=PythonAnalysisConfig(enabled=False))
        )
    )
    out = run_tokens("x = 1\n", config)
    assert all(o.status == "disabled" for o in out.observations)


def test_empty_source():
    out = by_id(run_tokens(""))
    assert out["code.python.lexical.token_class"].status == "insufficient_support"
    assert out["code.python.comments.comment_count"].value.value == 0
    assert out["code.python.comments.comment_line_share"].status == "insufficient_support"
